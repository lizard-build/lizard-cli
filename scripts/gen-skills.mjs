#!/usr/bin/env node
// Codegen step: inlines skill-data/<name>/SKILL.md and its references/*.md
// into a TypeScript module so the CLI can ship skills inside a Bun --compile binary,
// where fs paths to skill-data/ don't exist.
//
// Output: src/lib/skills-data.generated.ts (gitignored)

import { readdirSync, readFileSync, writeFileSync, statSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const srcDir = path.join(root, "skill-data");
const outFile = path.join(root, "src", "lib", "skills-data.generated.ts");

let names = [];
try {
  names = readdirSync(srcDir)
    .filter((n) => {
      try {
        return statSync(path.join(srcDir, n)).isDirectory();
      } catch {
        return false;
      }
    })
    .sort();
} catch (e) {
  console.error(`gen:skills: cannot read ${srcDir}: ${e.message}`);
  process.exit(1);
}

const entries = names.map((name) => {
  const file = path.join(srcDir, name, "SKILL.md");
  const content = readFileSync(file, "utf8");
  const refDir = path.join(srcDir, name, "references");
  let refs = [];
  try {
    refs = readdirSync(refDir).filter((f) => f.endsWith(".md")).sort();
  } catch {
    // no references/ directory
  }
  const references = refs.map((f) => ({
    name: f.slice(0, -3),
    content: readFileSync(path.join(refDir, f), "utf8"),
  }));
  return { name, content, references };
});

let out = "// AUTO-GENERATED by scripts/gen-skills.mjs — do not edit.\n";
out += "// Run `npm run gen:skills` to regenerate.\n\n";
out += "export interface EmbeddedSkill {\n";
out += "  name: string;\n";
out += "  content: string;\n";
out += "  /** references/<name>.md, keyed by <name> */\n";
out += "  references: Record<string, string>;\n";
out += "}\n\n";
out += "export const EMBEDDED_SKILLS: Record<string, EmbeddedSkill> = {\n";
for (const { name, content, references } of entries) {
  out += `  ${JSON.stringify(name)}: {\n`;
  out += `    name: ${JSON.stringify(name)},\n`;
  out += `    content: ${JSON.stringify(content)},\n`;
  out += "    references: {\n";
  for (const ref of references) {
    out += `      ${JSON.stringify(ref.name)}: ${JSON.stringify(ref.content)},\n`;
  }
  out += "    },\n";
  out += "  },\n";
}
out += "};\n";

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, out);
const refCount = entries.reduce((n, e) => n + e.references.length, 0);
console.log(
  `gen:skills wrote ${entries.length} skill(s), ${refCount} reference(s) to ${path.relative(root, outFile)}`,
);
